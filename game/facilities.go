const DiamondChance = 0.01

func FacilityCost(def FacilityDef, owned int) *Amount {
	return zeroAmount().Mul(amount(def.BaseCost), amountPow(facilityCostGrowth(def), owned))
}

func facilityCostGrowth(def FacilityDef) *Amount {
	if def.ID >= 81 {
		return amount("4")
	}
	if def.ID >= 71 {
		return amount("3")
	}
	if def.ID >= 61 {
		return amount("2.5")
	}
	if def.ID >= 51 {
		return amount("2")
	}
	if def.ID >= 41 {
		return amount("1.75")
	}
	if def.ID >= 31 {
		return amount("1.5")
	}
	if def.ID >= 21 {
		return amount("1.25")
	}
	return amount("1.05")
}

func ClickUpgradeCost(level int) *Amount {
	return zeroAmount().Mul(amount("100"), amountPow(amount("1.05"), level))
}

func ClickPower(level int) *Amount {
	return amountPow(amount("1.05"), level)
}

func FacilityUnitCPS(def FacilityDef, enhance int) *Amount {
	if enhance < 0 {
		enhance = 0
	}
	unit := zeroAmount().Mul(
		amount(def.BaseCPS),
		amountPow(facilityEnhanceGrowth(def), enhance),
	)
	return unit.Mul(unit, amountPow(amount("2"), enhance/10))
}

func facilityEnhanceGrowth(def FacilityDef) *Amount {
	if def.ID >= 61 {
		return amount("1.35")
	}
	if def.ID >= 31 {
		return amount("1.2")
	}
	return amount("1.1")
}

func FacilityCPS(def FacilityDef, st FacilityState) *Amount {
	if st.Owned <= 0 {
		return zeroAmount()
	}
	return zeroAmount().Mul(FacilityUnitCPS(def, st.Enhance), amountInt(int64(st.Owned)))
}
